# Метка на карте стоит неточно: по углам между будкой, торцом дома с красными шапками, розовым домиком и белой
# будкой на кадрах видео окно — на ~15 м западнее метки вдоль фасада (у стыка с 16-этажной башней). Поэтому всё,
# что снято со спутника, ниже задано от метки и сдвигается на Z_SHIFT (см. конец файла); ближний двор под окном
# (проезд, парковка, площадка) — по видео, уже от окна.
#
# Система координат — как в Godot (метры, Y вверх), начало — окно Юрчика на фасаде:
#   +x — от фасада во двор, на азимут THETA (ССВ);  −z — вдоль фасада на ЗСЗ (к проспекту Семёна Палия);
#   +z — вдоль фасада на ВЮВ.  Пересчёт со спутника: en(E, N), где E/N — метры на восток/север от окна.
# Камера меню стоит у окна и смотрит в −z с поворотом во двор (+x), поэтому всё важное — в секторе x > 0, z < 0.
import math

THETA = 19.0                       # азимут нормали фасада дома Юрчика (по краю крыши и соседнему дому с красными шапками)


def en(e, n):
    """Метры на восток/север от окна (спутник) → Godot (x, z)."""
    t = math.radians(THETA)
    return (e * math.sin(t) + n * math.cos(t), e * math.cos(t) - n * math.sin(t))



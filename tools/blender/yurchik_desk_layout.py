def key_rows():
    """Клавиши: (x, y, w, h, латиница, кириллица) в единицах «u» от левого-заднего угла раскладки (y — к пользователю)."""
    keys = []

    def row(y, items, x=0.0):
        for it in items:
            if isinstance(it, (int, float)):      # пропуск
                x += it
                continue
            lab, w = (it if isinstance(it, tuple) else (it, 1.0))[:2]
            ru = it[2] if isinstance(it, tuple) and len(it) > 2 else ""
            keys.append((x, y, w, 1.0, lab, ru))
            x += w
        return x

    row(0, ["Esc", 1, "F1", "F2", "F3", "F4", 0.5, "F5", "F6", "F7", "F8", 0.5, "F9", "F10", "F11", "F12",
            0.25, "PrtSc", "ScrLk", "Pause"])
    ru1 = "Ё"
    r1 = [("`", 1, ru1)] + [c for c in "1234567890"] + ["-", "=", ("Bksp", 2.0)]
    row(1.5, r1 + [0.25, "Ins", "Home", "PgUp", 0.25, "Num", "/", "*", "-"])
    ru2 = "ЙЦУКЕНГШЩЗХЪ"
    r2 = [("Tab", 1.5)] + [(c, 1.0, ru2[i]) for i, c in enumerate("QWERTYUIOP[]")] + [("\\", 1.5)]
    row(2.5, r2 + [0.25, "Del", "End", "PgDn", 0.25, "7", "8", "9"])
    ru3 = "ФЫВАПРОЛДЖЭ"
    r3 = [("Caps", 1.75)] + [(c, 1.0, ru3[i]) for i, c in enumerate("ASDFGHJKL;'")] + [("Enter", 2.25)]
    row(3.5, r3 + [3.5, "4", "5", "6"])
    ru4 = "ЯЧСМИТЬБЮ."
    r4 = [("Shift", 2.25)] + [(c, 1.0, ru4[i]) for i, c in enumerate("ZXCVBNM,./")] + [("Shift", 2.75)]
    row(4.5, r4 + [1.25, "^", 1.25, "1", "2", "3"])
    r5 = [("Ctrl", 1.25), ("Win", 1.25), ("Alt", 1.25), ("", 6.25), ("Alt", 1.25), ("Win", 1.25), ("Menu", 1.25), ("Ctrl", 1.25)]
    row(5.5, r5 + [0.25, "<", "v", ">", 0.25, ("0", 2.0), "."])
    keys.append((21.5, 2.5, 1.0, 2.0, "+", ""))       # высокие клавиши цифрового блока
    keys.append((21.5, 4.5, 1.0, 2.0, "Ent", ""))

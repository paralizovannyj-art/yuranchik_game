def uv(name, table=None, size=None):
    """Прямоугольник атласа → (u0, v0, u1, v1) в UV Blender (v снизу вверх)."""
    table = table or A
    W, H = size or (ATLAS, ATLAS)
    x0, y0, x1, y1 = table[name]
    return (x0 / W, 1 - y1 / H, x1 / W, 1 - y0 / H)


